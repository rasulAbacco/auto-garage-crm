// Status follows stock unless an item sets it explicitly
const statusFor = (it) => {
  if (it.status) return it.status;
  if (it.quantity === 0) return "Out of Stock";
  if (it.quantity <= it.minimumStock) return "Low Stock";
  return "Available";
};

async function findOwner(arg) {
  if (!arg) return prisma.user.findFirst({ orderBy: { id: "asc" } });
  if (/^\d+$/.test(arg))
    return prisma.user.findUnique({ where: { id: Number(arg) } });
  return prisma.user.findUnique({ where: { email: arg } });
}

async function main() {
  const user = await findOwner(process.argv[2]);
  if (!user) {
    throw new Error(
      `User not found for "${process.argv[2] ?? "(first user)"}". Pass an email or user id.`,
    );
  }
  console.log(`🌱 Seeding inventory for user #${user.id} (${user.email})`);

  // Suppliers — only add the ones this user doesn't have yet
  const existing = await prisma.supplier.findMany({
    where: { userId: user.id },
    select: { supplierName: true },
  });
  const have = new Set(existing.map((s) => s.supplierName));
  const newSuppliers = suppliers
    .filter((s) => !have.has(s.supplierName))
    .map((s) => ({ ...s, userId: user.id }));

  if (newSuppliers.length) {
    await prisma.supplier.createMany({ data: newSuppliers });
  }
  console.log(
    `   Suppliers added: ${newSuppliers.length} (already had ${have.size})`,
  );

  // itemCode is unique per garage (@@unique([userId, itemCode])),
  // so plain codes like OIL-001 work for every garage.
  const codeFor = (it) => it.itemCode;

  const existingCodes = new Set(
    (
      await prisma.inventory.findMany({
        where: { userId: user.id, itemCode: { in: items.map(codeFor) } },
        select: { itemCode: true },
      })
    ).map((r) => r.itemCode),
  );

  const result = await prisma.inventory.createMany({
    data: items.map((it) => ({
      itemCode: codeFor(it),
      itemName: it.itemName,
      category: it.category,
      brand: it.brand || null,
      model: it.model || null,
      partNumber: it.partNumber || null,
      supplier: it.supplier || null,
      purchasePrice: it.purchasePrice,
      sellingPrice: it.sellingPrice,
      quantity: it.quantity,
      minimumStock: it.minimumStock,
      unit: it.unit,
      location: it.location || null,
      description: it.description || null,
      status: statusFor(it),
      userId: user.id,
    })),
    skipDuplicates: true,
  });

  console.log(`   Inventory items added: ${result.count} of ${items.length}`);
  if (existingCodes.size) {
    console.log(
      `   ${existingCodes.size} skipped (already seeded for this user): ${[...existingCodes].join(", ")}`,
    );
  }

  const total = await prisma.inventory.count({ where: { userId: user.id } });
  console.log(`   This user now has ${total} inventory items in total.`);
  console.log("✅ Done");
}

main()
  .catch((err) => {
    console.error("❌ Seed failed:", err.message);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
